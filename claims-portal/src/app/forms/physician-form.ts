/** Values carried from the employee section (EFU page 1) onto the attending physician form (EFU page 2). */
export interface PhysicianFormData {
  claimRef: string;
  policyNo: string;
  employeeName: string;
  employeeCode: string;
  patientName: string;
  relation: string;
  age: string;
  gender: string;
  hospital: string;
  admission: string;
  discharge: string;
  treatment: string;
  preAuth: string;
}

const DOCTOR_FIELDS = [
  'Diagnosis (with ICD code if known)',
  'Presenting complaints and duration',
  'Date of first consultation for this illness',
  'Procedure / surgery performed',
  'Type of anesthesia',
  'Is the condition related to a pre-existing illness? If yes, since when',
  'Is the condition related to an accident, alcohol or drug use?',
];

export function fileRef(d: PhysicianFormData): string {
  return /^MED-/.test(d.claimRef) ? d.claimRef : 'preview';
}

/** Generates the pre-filled attending physician form as a real PDF (jsPDF is loaded on demand). */
export async function downloadPhysicianPdf(d: PhysicianFormData): Promise<void> {
  const { jsPDF } = await import('jspdf');
  const doc = new jsPDF({ unit: 'pt', format: 'a4' });
  const W = doc.internal.pageSize.getWidth();
  const M = 40;
  let y = 48;

  doc.setFillColor(15, 27, 61);
  doc.rect(0, 0, W, 70, 'F');
  doc.setTextColor(255, 255, 255);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(15);
  doc.text('EFU Health Insurance Limited', M, 32);
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(10);
  doc.text('Group Health Claim Form · Page 2 · Attending Physician Statement', M, 50);
  doc.text(`Claim ref: ${d.claimRef}`, W - M, 32, { align: 'right' });
  doc.text(`Policy: ${d.policyNo}`, W - M, 50, { align: 'right' });

  y = 100;
  doc.setTextColor(17, 24, 39);
  const section = (title: string) => {
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(11);
    doc.setFillColor(238, 243, 254);
    doc.rect(M, y - 13, W - 2 * M, 20, 'F');
    doc.text(title, M + 8, y + 1);
    y += 24;
  };
  const pair = (label: string, value: string, x: number, width: number) => {
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(8.5);
    doc.setTextColor(107, 114, 128);
    doc.text(label.toUpperCase(), x, y);
    doc.setFontSize(10.5);
    doc.setTextColor(17, 24, 39);
    doc.text(value || '-', x, y + 14, { maxWidth: width - 8 });
  };

  section('A. Patient and hospitalization (completed from the employee’s claim)');
  const col = (W - 2 * M) / 3;
  pair('Patient name', d.patientName, M, col); pair('Relationship', d.relation, M + col, col); pair('Age / gender', `${d.age} / ${d.gender}`, M + 2 * col, col);
  y += 34;
  pair('Employee', `${d.employeeName} (${d.employeeCode})`, M, col); pair('Hospital', d.hospital, M + col, col * 2);
  y += 34;
  pair('Date of admission', d.admission, M, col); pair('Date of discharge', d.discharge, M + col, col); pair('Treatment', `${d.treatment} · pre-auth: ${d.preAuth}`, M + 2 * col, col);
  y += 44;

  section('B. To be completed by the treating physician');
  doc.setFontSize(10);
  for (const f of DOCTOR_FIELDS) {
    doc.setTextColor(55, 65, 81);
    doc.text(f, M, y);
    doc.setDrawColor(207, 214, 226);
    doc.line(M, y + 22, W - M, y + 22);
    doc.line(M, y + 40, W - M, y + 40);
    y += 58;
  }

  section('C. Physician declaration');
  doc.setFontSize(9);
  doc.setTextColor(75, 85, 99);
  doc.text('I certify that the information above is true to the best of my knowledge and that I personally treated the patient.', M, y, { maxWidth: W - 2 * M });
  y += 30;
  doc.setDrawColor(150, 160, 180);
  doc.rect(M, y, (W - 2 * M) / 2 - 10, 70);
  doc.rect(M + (W - 2 * M) / 2 + 10, y, (W - 2 * M) / 2 - 10, 70);
  doc.text('Physician name, qualification and PMDC no.', M + 6, y + 82);
  doc.text('Signature and hospital stamp', M + (W - 2 * M) / 2 + 16, y + 82);

  doc.setFontSize(8);
  doc.setTextColor(150, 155, 165);
  doc.text(`Generated by ESS Portal on ${new Date().toLocaleString('en-GB')}. Upload the signed copy to claim ${d.claimRef}.`, M, doc.internal.pageSize.getHeight() - 24);

  doc.save(`physician-form-${fileRef(d)}.pdf`);
}

